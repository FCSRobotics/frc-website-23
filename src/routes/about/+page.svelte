		<h2 id = "title" style="font-size: 35px;">Audrie Gardham Ulmer '37 Center for Innovation & Design</h2>
		<p>
			The Audrie Gardham Ulmer '37 Center for Innovation & Design (CID) was created in an 
			innovative project that transformed the Rex Gymnasium of Friends' Central School's upper 
			campus into a state-of-the-art engineering & design center. The project was led by our current 
			head of school, Beth Johnson, and has revolutionized the space, allowing all students on the 
			upper school campus to explore and discover their passion for STEM and design.
		</p>
		<p>
			With two stories filled to the brim with the tools required to innovate, the CID is a central
			space for anyone looking to learn about design. The main group that uses it is the robotics
			team, with the first floor being partially taken over by them during the build season, but
			it's also used for projects in both middle and high school classes, such as the eighth
			grade science class's Rube Goldberg project. 
		</p>

		<p>
			Students are also allowed to use the CID for personal projects, with many spending their
			free time to bring their ideas to life, such as a go-kart, drone, and full-scale replica of
			a London telephone booth. The robotics team helps to maintain the CID, and promotes its core
			values of innovation, teamwork, and design for the entire school to see.
		</p>
